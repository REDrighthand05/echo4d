package echo.harness

import echo.shared.CaptureWriter
import echo.shared.Convert
import echo.shared.DepthDownsample
import echo.shared.JsonObj
import echo.shared.StampClock
import java.io.File

/**
 * Desktop proof harness: drives the ANDROID app's conversion code
 * (echo.shared) with synthetic Android-style raw events synthesised
 * from the committed simulated capture
 * (experiments/sensor_sim/capture_room2_sim), and writes a capture
 * folder exactly as the app would. android_collector/validate_capture.py
 * then checks that folder with the real Python reader + importer.
 *
 * The synthesis is the inverse of the app's conversions, by design:
 *  - IMU: the sim's device-frame accel/gyro pass through (the format's
 *    device frame IS Android's sensor frame — see Convert.kt), and the
 *    sim's world-from-device quaternion becomes a rotation-vector
 *    event (xyzw). The app path must hand back the sim's imu.csv.
 *  - Frames: SENSOR_TIMESTAMP = origin + t_s; the app stamps from the
 *    timestamp, so frames.csv must hand back the sim's times.
 *  - Depth: each sim ToF zone becomes a constant 10x10 block of an
 *    80x80 DEPTH16 image; the app's downsample must hand back the
 *    sim's zones.
 * The simulated phone is assigned SENSOR_ORIENTATION 0, so its
 * cam_from_device is the format's reference mounting diag(1,-1,-1) —
 * the same calibration the sim capture carries — and the payoff
 * importer therefore sees an equivalent capture.
 */

private fun readCsv(file: File): List<List<String>> =
    file.readLines().filter { it.isNotBlank() }.drop(1).map { it.split(",") }

fun main(args: Array<String>) {
    require(args.size == 2) { "usage: harness <sim_capture_dir> <out_dir>" }
    val sim = File(args[0])
    val out = File(args[1])
    out.mkdirs()

    val originNs = 987_654_321_000_000L // arbitrary monotonic-domain origin
    val clock = StampClock(originNs)
    val writer = CaptureWriter(out)
    fun ts(tSeconds: Double): Long = originNs + Math.round(tSeconds * 1e9)

    // --- frames ------------------------------------------------------
    val frames = readCsv(File(sim, "frames.csv"))
    for ((i, row) in frames.withIndex()) {
        val t = clock.stamp("frames", ts(row[1].toDouble()))
        writer.addFrame(i + 1, t, row[2])
    }

    // --- IMU ---------------------------------------------------------
    val imu = readCsv(File(sim, "imu.csv"))
    for (row in imu) {
        val v = row.map { it.toDouble() }
        // sim quat is wxyz world-from-device; the Android event is xyzw.
        val rotVec = floatArrayOf(
            v[2].toFloat(), v[3].toFloat(), v[4].toFloat(), v[1].toFloat()
        )
        val quatWxyz = Convert.rotationVectorToWxyz(rotVec)
        val t = clock.stamp("imu", ts(v[0]))
        writer.addImu(
            t, quatWxyz,
            doubleArrayOf(v[5], v[6], v[7]),
            doubleArrayOf(v[8], v[9], v[10])
        )
    }

    // --- ToF via synthetic DEPTH16 images -----------------------------
    val tof = readCsv(File(sim, "tof.csv"))
    val imgSize = 80
    val block = imgSize / 8
    for (row in tof) {
        val zones = (1..64).map { row[it].toInt() }
        val buf = ShortArray(imgSize * imgSize)
        for (z in 0 until 64) {
            val mm = zones[z]
            val packed: Short = if (mm <= 0) 0 else (mm or (7 shl 13)).toShort()
            val r0 = (z / 8) * block
            val c0 = (z % 8) * block
            for (y in r0 until r0 + block) {
                for (x in c0 until c0 + block) buf[y * imgSize + x] = packed
            }
        }
        val outZones = DepthDownsample.downsample(buf, imgSize, imgSize)
        val t = clock.stamp("tof", ts(row[0].toDouble()))
        writer.addTof(t, outZones)
    }

    writer.writeStreams()

    val camFd = Convert.camFromDevice(0)
    val duration = frames.last()[1].toDouble()
    val meta = JsonObj()
        .put("format_version", echo.shared.FORMAT_VERSION)
        .put("device", JsonObj()
            .put("name", "ECHO Collector")
            .put("board", "JVM harness (simulated Android)")
            .put("firmware", "android-collector-harness-1"))
        .put("simulated", true)
        .put(
            "provenance",
            "Generated by android_collector/harness from experiments/" +
                "sensor_sim/capture_room2_sim: the sim's streams were " +
                "re-emitted as synthetic Android raw events (rotation " +
                "vector, SENSOR_TIMESTAMPs, DEPTH16 images) and run " +
                "through the Android app's own conversion code. Proves " +
                "the app code path + format contract, not hardware."
        )
        .put("clock", JsonObj()
            .put("type", "monotonic")
            .put("unit", "s")
            .put("origin_note", "t=0 is capture start on the Android " +
                "elapsedRealtime clock (synthetic origin in the harness)"))
        .put("duration_s", duration)
        .put("streams", JsonObj()
            .put("video", JsonObj()
                .put("file", "video.mp4")
                .put("fps_nominal", 2.0)
                .put("frames_csv", "frames.csv")
                .put("note", "no video in harness output; frames.csv " +
                    "names follow the recorder convention"))
            .put("imu", JsonObj()
                .put("hz", 100.0)
                .put("quat_order", "wxyz")
                .put("accel_unit", "m/s^2 (device frame, incl. gravity)")
                .put("gyro_unit", "rad/s (device frame)"))
            .put("tof", JsonObj()
                .put("hz", 5.0)
                .put("grid", listOf(8, 8))
                .put("fov_deg", 45.0)
                .put("max_range_mm", 4000)
                .put("invalid", -1)
                .put("unit", "mm")))
        .put("calibration", JsonObj()
            .put("cam_from_device", camFd.map { it.toList() })
            .put("camera", null))
        .put("android", JsonObj()
            .put("backend", "harness")
            .put("simulated_sensor_orientation_deg", 0)
            .put("timestamp_source", "REALTIME (synthetic)"))
    writer.writeMeta(meta.render())

    println("harness capture written to $out")
    println("frames=${writer.frameCount} imu=${writer.imuCount} tof=${writer.tofCount}")
}
