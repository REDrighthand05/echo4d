"""Geometry data contracts and evidence provenance tags.

Defines standardized geometry representations, provenance tracking,
and export serialization for observed and structural meshes.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional
import numpy as np


class EvidenceSource(str, Enum):
    """Origin of 3D geometry vertices and surfaces."""
    OBSERVED = "OBSERVED"
    GEOMETRIC_INFERRED = "GEOMETRIC_INFERRED"
    AI_PROPOSED_VALIDATED = "AI_PROPOSED_VALIDATED"
    UNKNOWN = "UNKNOWN"


class StructuralCategory(str, Enum):
    """Semantic category of detected structural surfaces."""
    FLOOR = "floor"
    WALL = "wall"
    CEILING = "ceiling"
    OBJECT = "object"
    UNKNOWN = "unknown"


@dataclass
class PlaneModel:
    """Parametric plane representation: n . X + d = 0 with ||n|| = 1."""
    normal: np.ndarray  # shape (3,)
    distance: float     # scalar d
    inlier_indices: np.ndarray
    category: StructuralCategory = StructuralCategory.UNKNOWN
    confidence_heuristic: float = 0.5
    support_views: List[str] = field(default_factory=list)
    bounds_min: np.ndarray = field(
        default_factory=lambda: np.zeros(3, dtype=np.float64)
    )
    bounds_max: np.ndarray = field(
        default_factory=lambda: np.zeros(3, dtype=np.float64)
    )

    def to_dict(self) -> Dict[str, Any]:
        return {
            "normal": [float(x) for x in self.normal],
            "distance": float(self.distance),
            "inlier_count": int(len(self.inlier_indices)),
            "category": self.category.value,
            "confidence_heuristic": round(float(self.confidence_heuristic), 4),
            "support_views": self.support_views,
            "bounds_min": [float(x) for x in self.bounds_min],
            "bounds_max": [float(x) for x in self.bounds_max],
        }


@dataclass
class SceneGeometry:
    """Standardized representation of 3D surface geometry with provenance."""
    vertices: np.ndarray        # shape (N, 3), float64
    triangles: np.ndarray       # shape (M, 3), uint32
    normals: np.ndarray         # shape (N, 3), float64
    colors: np.ndarray          # shape (N, 3), uint8
    evidence_tags: np.ndarray   # shape (N,), object or str
    categories: np.ndarray      # shape (N,), object or str
    units: str = "meters"
    frame_id: str = "world"
    provenance: Dict[str, Any] = field(default_factory=dict)

    def __post_init__(self):
        n = len(self.vertices)
        if len(self.normals) != n:
            self.normals = np.zeros((n, 3), dtype=np.float64)
        if len(self.colors) != n:
            self.colors = np.full((n, 3), 200, dtype=np.uint8)
        if len(self.evidence_tags) != n:
            self.evidence_tags = np.full(n, EvidenceSource.OBSERVED.value, dtype=object)
        if len(self.categories) != n:
            self.categories = np.full(n, StructuralCategory.UNKNOWN.value, dtype=object)

    def write_ply(self, path: Path) -> None:
        """Export geometry to standard ASCII/binary PLY file with vertex colors."""
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        n_verts = len(self.vertices)
        n_tris = len(self.triangles)

        header = (
            "ply\n"
            "format binary_little_endian 1.0\n"
            f"comment Generated by Echo4D Geometry Engine\n"
            f"comment units {self.units}\n"
            f"element vertex {n_verts}\n"
            "property float x\n"
            "property float y\n"
            "property float z\n"
            "property float nx\n"
            "property float ny\n"
            "property float nz\n"
            "property uchar red\n"
            "property uchar green\n"
            "property uchar blue\n"
            f"element face {n_tris}\n"
            "property list uchar int vertex_indices\n"
            "end_header\n"
        )

        with open(path, "wb") as f:
            f.write(header.encode("ascii"))
            # Pack vertex data: 3 floats pos, 3 floats norm, 3 uchar color
            v_data = np.empty(
                n_verts,
                dtype=[
                    ("x", "<f4"), ("y", "<f4"), ("z", "<f4"),
                    ("nx", "<f4"), ("ny", "<f4"), ("nz", "<f4"),
                    ("r", "u1"), ("g", "u1"), ("b", "u1"),
                ],
            )
            v_data["x"] = self.vertices[:, 0]
            v_data["y"] = self.vertices[:, 1]
            v_data["z"] = self.vertices[:, 2]
            v_data["nx"] = self.normals[:, 0]
            v_data["ny"] = self.normals[:, 1]
            v_data["nz"] = self.normals[:, 2]
            v_data["r"] = self.colors[:, 0]
            v_data["g"] = self.colors[:, 1]
            v_data["b"] = self.colors[:, 2]
            f.write(v_data.tobytes())

            # Pack face data: uchar(3) followed by 3 uint32 indices
            if n_tris > 0:
                face_data = np.empty(
                    n_tris,
                    dtype=[
                        ("count", "u1"),
                        ("i0", "<u4"), ("i1", "<u4"), ("i2", "<u4"),
                    ],
                )
                face_data["count"] = 3
                face_data["i0"] = self.triangles[:, 0]
                face_data["i1"] = self.triangles[:, 1]
                face_data["i2"] = self.triangles[:, 2]
                f.write(face_data.tobytes())

    @classmethod
    def from_ply(cls, path: Path) -> "SceneGeometry":
        """Load vertex and face data from PLY file."""
        import open3d as o3d
        mesh = o3d.io.read_triangle_mesh(str(path))
        verts = np.asarray(mesh.vertices, dtype=np.float64)
        tris = np.asarray(mesh.triangles, dtype=np.uint32)
        if mesh.has_vertex_normals():
            normals = np.asarray(mesh.vertex_normals, dtype=np.float64)
        else:
            normals = np.zeros_like(verts)
        if mesh.has_vertex_colors():
            colors = np.clip(np.asarray(mesh.vertex_colors) * 255.0, 0, 255).astype(np.uint8)
        else:
            colors = np.full((len(verts), 3), 200, dtype=np.uint8)

        n = len(verts)
        return cls(
            vertices=verts,
            triangles=tris,
            normals=normals,
            colors=colors,
            evidence_tags=np.full(n, EvidenceSource.OBSERVED.value, dtype=object),
            categories=np.full(n, StructuralCategory.UNKNOWN.value, dtype=object),
        )
